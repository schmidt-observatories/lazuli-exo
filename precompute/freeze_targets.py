"""Generate src/lazuli_exo/targets.py from the NASA Exoplanet Archive (PSCompPars).

Run (needs astroquery, network):
    ~/anaconda3/envs/py313/bin/python precompute/freeze_targets.py
or offline from a saved TAP snapshot ({"pscomppars": [row, ...]} JSON):
    python precompute/freeze_targets.py --nea nea.json

Radius convention: one k = R_p/R_s per planet, frozen from the archive
pl_ratror when available (else pl_radj/st_rad); R_p_RJ is derived from k so
the runtime radius ratio and `depth` = k**2 cannot diverge (issue #7).
"""
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from lazuli_exo.atmosphere import R_J, R_SUN  # noqa: E402
from lazuli_exo.orbit import transit_duration_s  # noqa: E402

PLANETS = [
    "HD 209458 b", "HD 189733 b", "WASP-39 b", "WASP-96 b", "WASP-107 b",
    "WASP-121 b", "WASP-12 b", "HAT-P-11 b", "GJ 1214 b", "GJ 3470 b",
    "K2-18 b", "TOI-270 d", "TRAPPIST-1 e", "LHS 1140 b",
]

# Literature patches for archive gaps: {"planet": {"field": value}}.
# Add entries as the run below reports missing fields; comment each source.
OVERRIDES = {}

COLS = ("pl_name, pl_radj, pl_bmassj, pl_orbper, pl_trandur, pl_eqt, "
        "pl_ratror, pl_ratdor, pl_orbincl, pl_orbeccen, pl_orblper, "
        "st_rad, st_teff, st_logg, st_met, sy_jmag")

OUT = Path(__file__).resolve().parents[1] / "src" / "lazuli_exo" / "targets.py"

HEADER = '''"""Frozen showcase-target registry (GENERATED by precompute/freeze_targets.py).

Source: NASA Exoplanet Archive PSCompPars + OVERRIDES in freeze_targets.py.
Do not edit by hand; re-run the script to refresh.
"""

TARGETS = '''

FOOTER = '''

PLANET_NAMES = sorted(TARGETS)


def get_target(name):
    try:
        return TARGETS[name]
    except KeyError:
        raise KeyError(
            f"Unknown target {name!r}. Available: {PLANET_NAMES}") from None
'''


def fetch():
    from astroquery.ipac.nexsci.nasa_exoplanet_archive import NasaExoplanetArchive
    names = ",".join(f"'{p}'" for p in PLANETS)
    return NasaExoplanetArchive.query_criteria(
        table="pscomppars", select=COLS, where=f"pl_name in ({names})")


def val(row, col):
    v = row[col]
    try:
        v = float(v.value if hasattr(v, "value") else v)
    except (TypeError, ValueError):
        return None
    return None if math.isnan(v) else v


def _default(v, fallback):
    """Explicit missing-value default: only None (not a valid 0.0) falls
    back."""
    return fallback if v is None else v


def build_entry(row, name):
    ov = OVERRIDES.get(name, {})
    g = lambda field, raw: ov.get(field, raw)

    a_rs = val(row, "pl_ratdor")
    inc = g("inc_deg", _default(val(row, "pl_orbincl"), 90.0))
    teff = g("T_eff_K", val(row, "st_teff"))
    per = g("period_d", val(row, "pl_orbper"))
    r_s = g("R_s_RSun", val(row, "st_rad"))
    r_p_archive = g("R_p_RJ", val(row, "pl_radj"))

    # One radius ratio per planet (issue #7): prefer the archive's own
    # k = pl_ratror; the runtime's R_p_RJ is derived from it.
    rp_ratio = val(row, "pl_ratror")
    if rp_ratio is not None:
        k_source = "pl_ratror"
    elif r_p_archive and r_s:
        rp_ratio = r_p_archive * R_J / (r_s * R_SUN)
        k_source = "pl_radj/st_rad"
    else:
        k_source = None
    r_p = rp_ratio * r_s * R_SUN / R_J if rp_ratio and r_s else None

    # A NULL omega with a nonzero e would put the transit at periastron
    # (w = 90): treat the orbit as circular instead.
    ecc = g("ecc", _default(val(row, "pl_orbeccen"), 0.0))
    w_deg = g("w_deg", val(row, "pl_orblper"))
    ecc_note = None
    if w_deg is None:
        ecc, w_deg = 0.0, 90.0
        ecc_note = "w unavailable; circular assumed"

    # T_eq stays the archive value (the POSEIDON validation tables were built
    # at it); T_eq_conv_K is the A=0 full-redistribution value for reference.
    t_eq_conv = teff * math.sqrt(0.5 / a_rs) if teff and a_rs else None
    t_eq = val(row, "pl_eqt")
    if t_eq is None:
        t_eq = t_eq_conv

    t14 = val(row, "pl_trandur")          # hours in the archive
    t14_s = t14 * 3600.0 if t14 is not None else None
    if t14_s is None and per and a_rs and rp_ratio:
        t14_s = transit_duration_s(per, a_rs, rp_ratio, inc_deg=inc,
                                   ecc=ecc, w_deg=w_deg)

    entry = {
        "name": name,
        "slug": name.lower().replace(" ", "-"),
        "R_p_RJ": r_p,
        "R_p_archive_RJ": r_p_archive,
        "k_source": k_source,
        "M_p_MJ": g("M_p_MJ", val(row, "pl_bmassj")),
        "R_s_RSun": r_s,
        "T_eff_K": teff,
        "log_g_star": g("log_g_star", val(row, "st_logg")),
        "Met_star": g("Met_star", _default(val(row, "st_met"), 0.0)),
        "T_eq_K": g("T_eq_K", t_eq),
        "T_eq_conv_K": t_eq_conv,
        "period_d": per,
        "t14_s": g("t14_s", t14_s),
        "depth": rp_ratio ** 2 if rp_ratio else None,
        "a_over_rs": g("a_over_rs", a_rs),
        "inc_deg": inc,
        "ecc": ecc,
        "w_deg": w_deg,
        "J_mag": g("J_mag", val(row, "sy_jmag")),
        "provenance": "NEA PSCompPars"
                      + (" + overrides" if name in OVERRIDES else ""),
    }
    missing = [k for k, v in entry.items() if v is None]
    if missing:
        raise SystemExit(f"{name}: missing {missing} — add to OVERRIDES")
    if ecc_note:
        entry["ecc_note"] = ecc_note
    return entry


def main(argv=tuple(sys.argv[1:])):
    if argv[:1] == ("--nea",):
        import json
        table = json.load(open(argv[1]))["pscomppars"]
    else:
        table = fetch()
    rows = {str(r["pl_name"]): r for r in table}
    targets = {}
    for name in PLANETS:
        if name not in rows:
            raise SystemExit(f"{name} not returned by the archive query")
        targets[name] = build_entry(rows[name], name)
    import pprint
    body = pprint.pformat(targets, width=79, sort_dicts=True)
    OUT.write_text(HEADER + body + FOOTER)
    print(f"Wrote {OUT} with {len(targets)} targets")


if __name__ == "__main__":
    main()
